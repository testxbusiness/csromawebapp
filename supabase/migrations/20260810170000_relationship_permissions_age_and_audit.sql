create or replace function private.audit_profile_relationship_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth, private
as $$
declare
  v_actor_auth_user_id uuid := auth.uid();
  v_actor_profile_id uuid;
  v_actor_name text;
  v_action text;
  v_relationship_id uuid;
  v_source_profile_id uuid;
  v_target_profile_id uuid;
  v_details jsonb;
begin
  select aa.owner_profile_id, concat_ws(' ', p.first_name, p.last_name)
    into v_actor_profile_id, v_actor_name
  from public.app_accounts aa
  join public.profiles p on p.id = aa.owner_profile_id
  where aa.auth_user_id = v_actor_auth_user_id
  limit 1;

  if tg_op = 'INSERT' then
    v_action := 'created';
    v_relationship_id := new.id;
    v_source_profile_id := new.source_profile_id;
    v_target_profile_id := new.target_profile_id;
    v_details := jsonb_build_object('new', to_jsonb(new));
  elsif tg_op = 'UPDATE' then
    v_action := case
      when old.status <> 'revoked' and new.status = 'revoked' then 'revoked'
      else 'modified'
    end;
    v_relationship_id := new.id;
    v_source_profile_id := new.source_profile_id;
    v_target_profile_id := new.target_profile_id;
    v_details := jsonb_build_object('old', to_jsonb(old), 'new', to_jsonb(new));
  else
    v_action := 'deleted';
    v_relationship_id := old.id;
    v_source_profile_id := old.source_profile_id;
    v_target_profile_id := old.target_profile_id;
    v_details := jsonb_build_object('old', to_jsonb(old));
  end if;

  insert into public.profile_relationship_audit (
    relationship_id,
    source_profile_id,
    target_profile_id,
    action,
    performed_by_auth_user_id,
    actor_profile_id,
    actor_name_snapshot,
    details
  ) values (
    v_relationship_id,
    v_source_profile_id,
    v_target_profile_id,
    v_action,
    v_actor_auth_user_id,
    v_actor_profile_id,
    nullif(v_actor_name, ''),
    v_details
  );

  return coalesce(new, old);
end;
$$;

