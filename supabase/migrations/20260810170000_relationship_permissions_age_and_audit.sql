create or replace function private.is_profile_minor(
  p_profile_id uuid,
  p_at_date date default current_date
)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $$
  select coalesce(
    (
      select pao.treat_as_minor
      from public.profile_age_overrides pao
      where pao.profile_id = p_profile_id
        and pao.active
      order by pao.overridden_at desc
      limit 1
    ),
    (
      select case
        when p.birth_date is null then true
        else p_at_date < (p.birth_date + interval '18 years')::date
      end
      from public.profiles p
      where p.id = p_profile_id
    ),
    true
  )
$$;

create or replace function private.has_active_relationship_permission(
  p_target_profile_id uuid,
  p_permission text
)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $$
  select exists (
    select 1
    from public.profile_relationships pr
    where pr.source_profile_id = (select private.current_profile_id())
      and pr.target_profile_id = p_target_profile_id
      and pr.status = 'active'
      and pr.valid_from <= current_date
      and (pr.valid_until is null or pr.valid_until >= current_date)
      and case p_permission
        when 'view_schedule' then pr.can_view_schedule
        when 'confirm_attendance' then pr.can_confirm_attendance
        when 'view_payments' then pr.can_view_payments
        when 'view_medical_status' then pr.can_view_medical_status
        when 'view_documents' then pr.can_view_documents
        when 'sign_documents' then pr.can_sign_documents
        when 'receive_messages' then pr.can_receive_messages
        else false
      end
      and (
        (
          (select private.is_profile_minor(p_target_profile_id))
          and pr.relationship_type in ('parent', 'guardian', 'caregiver', 'delegate')
        )
        or (
          not (select private.is_profile_minor(p_target_profile_id))
          and pr.relationship_type = 'delegate'
          and pr.verified_at is not null
        )
      )
  )
$$;

