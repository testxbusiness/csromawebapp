create table if not exists public.profile_age_overrides (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null
    references public.profiles (id) on delete restrict,
  treat_as_minor boolean not null,
  reason text not null
    constraint profile_age_overrides_reason_check
    check (char_length(btrim(reason)) >= 10),
  overridden_by_auth_user_id uuid
    references auth.users (id) on delete set null,
  overridden_at timestamptz not null default now(),
  active boolean not null default true,
  revoked_by_auth_user_id uuid
    references auth.users (id) on delete set null,
  revoked_at timestamptz,
  revocation_reason text,
  constraint profile_age_overrides_revocation_check
    check (
      (active and revoked_at is null and revoked_by_auth_user_id is null)
      or (not active and revoked_at is not null)
    )
);

create unique index if not exists profile_age_overrides_active_profile_idx
  on public.profile_age_overrides (profile_id)
  where active = true;

create index if not exists profile_age_overrides_profile_idx
  on public.profile_age_overrides (profile_id, overridden_at desc);

